// Mastra tool for sending Slack notifications
export const sendSlackNotificationTool = createTool({
  id: "sendSlackNotification",
  description: "Send a notification message to a Slack channel via webhook",
  inputSchema: z.object({
    webhookUrl: z.string().describe("Slack webhook URL"),
    channel: z.string().optional().describe("Slack channel (optional if webhook is configured for specific channel)"),
    message: z.string().describe("Message to send to Slack"),
  }),
  outputSchema: z.object({
    success: z.boolean().describe("Whether the notification was sent successfully"),
    message: z.string().describe("Success or error message"),
  }),
  execute: async ({ context }) => {
    const { webhookUrl, channel, message } = context;
    return await sendSlackNotification({ webhookUrl, channel, message });
  },
});
