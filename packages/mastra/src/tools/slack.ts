// Direct function for use in workflows
export const sendSlackNotification = async (params: {
  webhookUrl: string;
  channel?: string;
  message: string;
}) => {
  const { webhookUrl, channel, message } = params;
  
  const payload = {
    text: message,
    ...(channel && { channel }),
  };

  try {
    const response = await fetch(webhookUrl, {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
      },
      body: JSON.stringify(payload),
    });

    if (!response.ok) {
      throw new Error(`Slack API error: ${response.status} ${response.statusText}`);
    }

    return {
      success: true,
      message: "Notification sent successfully",
    };
  } catch (error) {
    throw new Error(`Failed to send Slack notification: ${error instanceof Error ? error.message : 'Unknown error'}`);
  }
};

